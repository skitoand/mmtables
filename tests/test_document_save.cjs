const assert = require('node:assert/strict');
const {createQueue, createDraftStore} = require('../document-save.js');
const tick = () => new Promise(resolve => setImmediate(resolve));
const deferred = () => {let resolve,reject;const promise=new Promise((a,b)=>{resolve=a;reject=b});return {promise,resolve,reject}};
const job = (key, text, base='v1') => ({key,docId:key,base,layout:{sheets:[{text}]}});
(async () => {
  const requests=[], saved=[], errors=[];
  const q=createQueue({send:(j,base)=>{const d=deferred();requests.push({j,base,...d});return d.promise},onSaved:(j,b,r)=>saved.push([j,b,r]),onError:(j,e)=>errors.push(e)});
  q.setVersion('a','v1');q.setVersion('b','other-v1');
  const a=q.enqueue(job('a','A'));
  const b=q.enqueue(job('a','B'));
  const c=q.enqueue(job('a','C'));
  const other=q.enqueue(job('b','OTHER'));
  assert.equal(requests.length,1,'Only one request may be in flight');
  requests[0].resolve({updatedAt:'v2'});await a;await tick();
  assert.equal(requests.length,2);assert.equal(requests[1].base,'v2');assert.equal(requests[1].j.layout.sheets[0].text,'C','Latest queued input supersedes the intermediate snapshot');
  requests[1].resolve({updatedAt:'v3'});await Promise.all([b,c]);await tick();
  assert.equal(requests[2].base,'other-v1','Another document never borrows this document’s version');
  requests[2].resolve({updatedAt:'other-v2'});await other;await q.idle();
  assert.equal(q.version('a'),'v3');assert.equal(q.version('b'),'other-v2');
  const conflict=q.enqueue(job('a','D')).catch(e=>e);
  const pending=q.enqueue(job('a','E')).catch(e=>e);
  requests[3].reject(Object.assign(new Error('conflict'),{status:409}));
  assert.equal((await conflict).status,409);assert.equal((await pending).status,409);await q.idle();
  await assert.rejects(q.enqueue(job('a','F')),e=>e.status===409);
  assert.equal(requests.length,4,'Conflict blocks later writes instead of retrying against a newer version');
  q.setVersion('a','v5');const retry=q.enqueue(job('a','G'));
  requests[4].reject(new Error('offline'));await assert.rejects(retry,/offline/);await q.idle();
  assert.equal(q.version('a'),'v5','An unsuccessful write never advances the base');
  const next=q.enqueue(job('a','G'));requests[5].resolve({updatedAt:'v6'});await next;

  const storage=new Map();let quota=false;
  const store=createDraftStore({getItem:k=>storage.get(k),setItem:(k,v)=>{if(quota)throw Error('quota');storage.set(k,v)},removeItem:k=>storage.delete(k)});
  const key='alice\na', secondAccount='bob\na';
  const older=job('a','old').layout, newer=job('a','new').layout;
  store.write(key,{base:'v1',layout:newer,name:'Test'});
  assert.equal(store.read(secondAccount),null,'Drafts are isolated by user and document');
  assert.equal(store.acknowledge(key,older,'v1','v2'),false);
  assert.deepEqual(store.read(key).layout,newer,'A late acknowledgement never deletes newer keystrokes');
  assert.equal(store.read(key).base,'v2');
  quota=true;assert.equal(store.write(key,{base:'v2',layout:older}),false);assert.deepEqual(store.read(key).layout,newer);
  quota=false;assert.equal(store.acknowledge(key,newer,'v2','v3'),true);assert.equal(store.read(key),null);
  console.log('Document save queue/drafts: serialized/coalesced saves, scoped versions, 409 pause, network retry, account isolation, late acknowledgements and storage failure — passed');
})().catch(e=>{console.error(e);process.exitCode=1});
